// 清单是调用契约事实源；公共 C++ 协议生成到自包含插件中以支持独立拆仓。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const selected = process.argv.find(a => a.startsWith('--plugin='))?.split('=')[1];
const plugins = selected ? [selected] : ['march7th', 'zzz', 'maaend'];
for (const id of plugins) {
  if (!['march7th', 'zzz', 'maaend'].includes(id)) throw new Error(`Unknown adapter: ${id}`);
  const base = resolve(root, 'bridges', id, 'plugins', id);
  const manifest = JSON.parse(readFileSync(resolve(base, '.pudding-plugin/plugin.json'), 'utf8'));
  const methods = manifest.httpTools.map(t => ({
    id: `tool.${t.name}`, title: t.title, kind: 'tool', summary: t.description,
    source: 'pluginManifest', availability: 'registered', bridgeSupported: true,
    callable: null, callabilityVerified: false, executionVerified: false,
    agentCall: { tool: `${id}.http.${t.name}`, inputSchema: t.inputSchema },
    effect: t.execution.effect, exposure: t.execution.exposure,
    fallbackOnly: t.name.startsWith('host.'),
    next: t.name.startsWith('host.') ? '仅补足本轮常规接口缺口；先取得桥签发的 gapId、现场 memberId 并预览，不作为常规使用。' : '按 inputSchema 取得当前对象与版本证据；已登记不等于宿主当前可用。',
  }));
  const json = JSON.stringify(methods);
  const revision = createHash('sha256').update(json).digest('hex');
  const chunks = [];
  for (let i = 0; i < json.length; i += 3000) chunks.push(`R"PD(${json.slice(i, i + 3000)})PD"`);
  const outputs = {
    'disclosure.hpp': readFileSync(resolve(root, 'packages/bridge-disclosure/disclosure.hpp'), 'utf8'),
    'contracts.hpp': '#pragma once\nnamespace pudding::disclosure {\ninline constexpr const char* kContractVersion = "' + revision + '";\ninline constexpr const char* kContracts =\n' + chunks.join('\n') + ';\n}\n',
  };
  if (id !== 'maaend') outputs['python_view.hpp'] = readFileSync(resolve(root, 'packages/bridge-disclosure/python_view.hpp'), 'utf8');
  for (const [name, content] of Object.entries(outputs)) {
    const path = resolve(base, 'bridge/generated', name);
    const text = '// Generated by scripts/generate-adapter-disclosure.mjs. DO NOT EDIT.\n' + content;
    let old; try { old = readFileSync(path, 'utf8'); } catch {}
    if (old === text) continue;
    if (check) throw new Error(`Stale generated adapter source: ${path}`);
    mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text);
  }
}
console.log(`Adapter disclosure ${check ? 'verified' : 'generated'}: ${plugins.join(', ')}`);
